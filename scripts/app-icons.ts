// Regenerates server/appIconPng.ts: the PNG renders of ICON_SVG that the
// manifest and apple-touch-icon point at. Rerun after changing the icon art:
//
//   node scripts/app-icons.ts

import { chromium } from "@playwright/test";
import { writeFileSync } from "node:fs";
import { ICON_SIZES, ICON_SVG } from "../server/appIcon.ts";

const browser = await chromium.launch();
const out: string[] = [];
try {
  for (const size of ICON_SIZES) {
    const page = await browser.newPage({ viewport: { width: size, height: size } });
    await page.setContent(
      `<style>html,body{margin:0}svg{display:block;width:${size}px;height:${size}px}</style>${ICON_SVG}`,
    );
    const png = await page.screenshot({ type: "png", omitBackground: false });
    out.push(`  ${size}: "${png.toString("base64")}",`);
    await page.close();
  }
} finally {
  await browser.close();
}

writeFileSync(
  new URL("../server/appIconPng.ts", import.meta.url),
  `// Generated by scripts/app-icons.ts from ICON_SVG; do not edit.\n\nexport const ICON_PNG_BASE64: Record<number, string> = {\n${out.join("\n")}\n};\n`,
);
console.log(`wrote ${ICON_SIZES.length} icons`);
